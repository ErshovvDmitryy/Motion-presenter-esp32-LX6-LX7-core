#pragma once

// ============================================================================
// ЕДИНАЯ КОНФИГУРАЦИЯ МОДЕЛИ / ОКНА / ДАТАСЕТА
// ============================================================================
// Все настройки окна и инференса живут здесь — один источник правды.
// Смена датасета = подключить новый gesture_model_data.h и поправить
// MODEL_WINDOW (обязан совпадать с input[1] модели), при желании - stride.

// Длина окна (семплов). Равна второму элементу входного тензора модели [1, WINDOW, 6].
#define MODEL_WINDOW   49

// Число признаков на семпл (ax, ay, az, gx, gy, gz).
#define MODEL_FEATURES 6

// Число классов модели (совпадает с числом строк class_names.txt).
#define MODEL_CLASSES  8

// Шаг (stride) скользящего окна детекции в семплах.
// Соответствует нарезке датасета: окна 0-80, 20-100, 40-120...
#define MODEL_STRIDE   10

// Запас буфера поверх окна (позволяет окну "скользить" по свежим сэмплам).
#define MODEL_BIAS     20

// Интервал (мс) между инференсами при безостановочной детекции.
// 40 мс = ~25 детекций/с — стабильно и не грузит цикл.
#define DETECT_INTERVAL_MS 25

// Минимальная уверенность класса свайпа для фиксации детекции.
#define DETECT_CONF_THRESH 0.80f

// Сколько последовательных согласованных окон нужно, чтобы зафиксировать жест
// (защита от ложных свайпов по одному окну). 1 = реагировать сразу на одно окно.
#define DETECT_VOTE_N 1

// Пауза (мс) после отправки HID, до которой новые детекции игнорируются.
#define HID_COOLDOWN_MS 800

// Размер тензорной арены TFLM (может потребоваться под конкретную модель).
#define MODEL_ARENA_BYTES (80 * 1024)

// ============================================================================
// Производные (не менять вручную)
// ============================================================================
#define MOTION_BUFFER (MODEL_WINDOW + MODEL_BIAS)
#define NUM_INPUTS    (MODEL_WINDOW * MODEL_FEATURES)